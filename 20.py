print("Звенит будильник. Утро. Что делаешь?")
step1 = input("Встать или спать дальше? (встать/спать): ")

if step1 == "встать":
    step2 = input("Ты умылся. Позавтракать или сразу бежать? (завтрак/бежать): ")
    if step2 == "завтрак":
        step3 = input("Что ешь на завтрак? Кашу или бутерброд? (каша/бутерброд): ")
        if step3 == "каша":
            print("Конец 1: Сытная каша дала сил. Ты пришёл вовремя и сдал всё на отлично!")
        else:
            print("Конец 2: Бутерброд был вкусным, но ты чуть не опоздал. Зато успел!")
    else:
        step3 = input("Как добираешься? На автобусе или пешком? (автобус/пешком): ")
        if step3 == "автобус":
            print("Конец 3: Автобус застрял в пробке. Ты опоздал, но преподаватель вошёл в положение.")
        else:
            print("Конец 4: Ты прибежал первым, но голодный. Зато не опоздал и получил заряд бодрости!")

elif step1 == "спать":
    step2 = input("Ты проспал. Позвонить другу или бежать самому? (позвонить/бежать): ")
    if step2 == "позвонить":
        step3 = input("Друг не берёт трубку. Написать смс или пойти в универ? (смс/пойти): ")
        if step3 == "смс":
            print("Конец 5: Друг ответил, что пары отменили. Ты спасён и спишь дальше!")
        else:
            print("Конец 6: Пришёл в универ, а там никого. Оказалось, правда отменили. Придётся идти домой.")
    else:
        step3 = input("Ты выбежал из дома. Взять такси или бежать? (такси/бежать): ")
        if step3 == "такси":
            print("Конец 7: Таксист домчал тебя за 5 минут. Ты успел на первую пару!")
        else:
            print("Конец 8: Ты бежал со всех ног, влетел в аудиторию, и все зааплодировали.")

else:
    print("Конец 9: Ты не понял будильник и выключил его. Проспал до вечера.")